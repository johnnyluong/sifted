import { fileURLToPath } from "node:url";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";
import ts from "typescript";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const OUT = fileURLToPath(new URL("../src/api/schema.gen.ts", import.meta.url));
const HEADER = "// Generated by `bun run api` from FastAPI's OpenAPI document (sift/web/openapi.py). Do not edit.\n\n";
// A binary request body (the import zip) is a string by default; openapi-fetch needs Blob to send a File.
const BLOB = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier("Blob"));

export async function render(doc: OpenAPI3): Promise<string> {
  const ast = await openapiTS(doc, {
    enumValues: true,
    rootTypes: true,
    rootTypesNoSchemaPrefix: true,
    transform: (schema) => (schema.format === "binary" ? BLOB : undefined),
  });
  return HEADER + astToString(ast);
}

async function openapiDocument(): Promise<OpenAPI3> {
  const proc = Bun.spawnSync(["uv", "run", "python", "-m", "sift.web.openapi"], { cwd: ROOT, stderr: "inherit" });
  if (proc.exitCode !== 0) throw new Error("`uv run python -m sift.web.openapi` failed");
  return JSON.parse(proc.stdout.toString());
}

async function main(check: boolean): Promise<number> {
  const next = await render(await openapiDocument());
  if (!check) {
    await Bun.write(OUT, next);
    return 0;
  }
  const current = await Bun.file(OUT)
    .text()
    .catch(() => "");
  if (current === next) return 0;
  console.error("src/api/schema.gen.ts is out of date with the API. Run: bun run --cwd web api");
  return 1;
}

if (import.meta.main) process.exit(await main(process.argv.includes("--check")));
